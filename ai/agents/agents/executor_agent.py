from __future__ import annotations
from typing import Dict, Any, List
import logging
from ...remediation.remediation_engine import execute_action

# Configure logger for observability
logger = logging.getLogger(__name__)

class ExecutorAgent:
    """
    Executor Agent.
    Responsible for safely carrying out the remediation plans generated by the Planner.
    """
    def __init__(self, config: Dict[str, Any]):
        self.config = config
        # Default to 'dry_run' for safety if not explicitly set to 'active'
        self.mode = config.get('mode', 'dry_run') 
        logger.info(f"ExecutorAgent initialized in mode: {self.mode}")

    def execute(self, plan: Dict[str, Any]) -> Dict[str, Any]:
        """
        Executes the list of actions defined in the plan.
        Returns a structured execution report.
        """
        actions = plan.get('planned_actions', [])
        report = {
            'status': 'completed',
            'mode': self.mode,
            'total_actions': len(actions),
            'executed': [],
            'failed': []
        }

        if not actions:
            logger.warning("Executor received an empty plan. No actions to take.")
            report['status'] = 'skipped'
            return report

        logger.info(f"Starting execution of {len(actions)} actions...")

        for action in actions:
            try:
                if self.mode == 'dry_run':
                    # Simulate execution
                    logger.info(f"[DRY RUN] Would execute: {action}")
                    report['executed'].append({'action': action, 'result': 'simulated'})
                else:
                    # Live execution
                    logger.info(f"Executing: {action}")
                    execute_action(action)
                    report['executed'].append({'action': action, 'result': 'success'})

            except Exception as e:
                logger.error(f"Action Failed: {action} | Error: {str(e)}")
                report['failed'].append({'action': action, 'error': str(e)})
        
        # Determine final status
        if report['failed']:
            report['status'] = 'partial_failure' if report['executed'] else 'failed'
            
        return report
